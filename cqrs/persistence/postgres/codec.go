package postgres

import (
	"context"

	"eventsalsa.dev/store"
)

// EventCodec encodes domain events into store.Event records and decodes
// persisted events back into domain events.
type EventCodec[E any] interface {
	Encode(ctx context.Context, streamType, streamID string, event E) (store.Event, error)
	Decode(ctx context.Context, pe store.PersistedEvent) (E, error)
}

// FuncEventCodec adapts plain EncodeFunc and DecodeFunc closures to EventCodec[E].
type FuncEventCodec[E any] struct {
	EncodeFunc func(ctx context.Context, streamType, streamID string, event E) (store.Event, error)
	DecodeFunc func(ctx context.Context, pe store.PersistedEvent) (E, error)
}

func (c FuncEventCodec[E]) validate() error {
	if c.EncodeFunc == nil || c.DecodeFunc == nil {
		return ErrNilCodec
	}
	return nil
}

// Encode encodes event using EncodeFunc, returning ErrNilCodec if unset.
func (c FuncEventCodec[E]) Encode(ctx context.Context, streamType, streamID string, event E) (store.Event, error) {
	if c.EncodeFunc == nil {
		return store.Event{}, ErrNilCodec
	}
	return c.EncodeFunc(ctx, streamType, streamID, event)
}

// Decode decodes pe using DecodeFunc, returning ErrNilCodec if unset.
//
//nolint:gocritic // hugeParam: matches store.PersistedEvent value contract
func (c FuncEventCodec[E]) Decode(ctx context.Context, pe store.PersistedEvent) (E, error) {
	if c.DecodeFunc == nil {
		var zero E
		return zero, ErrNilCodec
	}
	return c.DecodeFunc(ctx, pe)
}

// NewEventMapCodec constructs an EventCodec[E] directly from MarshalEvent and
// FromESEventAs[E] functions generated by eventsalsa.dev/store/cmd/eventmap-gen.
func NewEventMapCodec[E any](
	marshal func(event any) (eventType string, version int, payload []byte, err error),
	unmarshal func(pe store.PersistedEvent) (E, error),
) (EventCodec[E], error) {
	if marshal == nil || unmarshal == nil {
		return nil, ErrNilCodec
	}
	return FuncEventCodec[E]{
		EncodeFunc: func(_ context.Context, streamType, streamID string, event E) (store.Event, error) {
			eventType, version, payload, err := marshal(event)
			if err != nil {
				return store.Event{}, err
			}
			return store.Event{
				StreamType:   streamType,
				StreamID:     streamID,
				EventType:    eventType,
				EventVersion: version,
				Payload:      payload,
			}, nil
		},
		DecodeFunc: func(_ context.Context, pe store.PersistedEvent) (E, error) {
			return unmarshal(pe)
		},
	}, nil
}
